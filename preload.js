const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  loadData: () => ipcRenderer.invoke('data:load'),
  saveData: (data) => ipcRenderer.invoke('data:save', data),
  pickFolder: () => ipcRenderer.invoke('dialog:folder'),
  subdirs: (dir) => ipcRenderer.invoke('fs:subdirs', dir),
  playSystemSound: (name, volume) => ipcRenderer.send('sound:system', name, volume),
  updateStatus: () => ipcRenderer.invoke('app:update-status'),
  rebuild: (openCount) => ipcRenderer.invoke('app:rebuild', openCount),
  onRebuildLog: (cb) => ipcRenderer.on('app:rebuild-log', (_e, text) => cb(text)),
  usage: (configDir) => ipcRenderer.invoke('usage:get', configDir),
  clickupStatus: () => ipcRenderer.invoke('clickup:status'),
  clickupSetToken: (token) => ipcRenderer.invoke('clickup:set-token', token),
  clickupTask: (ref) => ipcRenderer.invoke('clickup:task', ref),
  clickupCheckStatuses: (dir, names) => ipcRenderer.invoke('clickup:check-statuses', dir, names),
  clickupHierarchy: () => ipcRenderer.invoke('clickup:hierarchy'),
  clickupInbox: (sources, statuses, mineStatuses) => ipcRenderer.invoke('clickup:inbox', sources, statuses, mineStatuses),
  clickupAssignMe: (taskId) => ipcRenderer.invoke('clickup:assign-me', taskId),
  clickupAdvance: (taskId, allowed, target) => ipcRenderer.invoke('clickup:advance', taskId, allowed, target),
  clickupTimes: (start, end) => ipcRenderer.invoke('clickup:times', start, end),
  clickupAlign: (dir, taskId) => ipcRenderer.invoke('clickup:align', dir, taskId),
  clickupTimePending: () => ipcRenderer.invoke('clickup:time-pending'),
  clickupTimeConfirm: (id, duration) => ipcRenderer.invoke('clickup:time-confirm', id, duration),
  onClickupTimePending: (cb) => ipcRenderer.on('clickup:time-pending', (_e, p) => cb(p)),
  onClickupSync: (cb) => ipcRenderer.on('clickup:sync', (_e, ev) => cb(ev)),
  kanbanRead: (dir) => ipcRenderer.invoke('kanban:read', dir),
  kanbanWrite: (dir, tasks) => ipcRenderer.invoke('kanban:write', dir, tasks),
  kanbanWatch: (dir) => ipcRenderer.send('kanban:watch', dir),
  onKanbanChanged: (cb) => ipcRenderer.on('kanban:changed', (_e, dir) => cb(dir)),
  bgPick:() => ipcRenderer.invoke('bg:pick'),
  bgRead: (file) => ipcRenderer.invoke('bg:read', file),
  scanSkills: (projectDirs, configDir) => ipcRenderer.invoke('skills:scan', projectDirs, configDir),
  gitTrack: (cwd) => ipcRenderer.invoke('git:track', cwd),
  gitUntrack: (root) => ipcRenderer.send('git:untrack', root),
  gitDiff: (repos, sinceBaseline) => ipcRenderer.invoke('git:diff', repos, sinceBaseline),
  onGitChanged: (cb) => ipcRenderer.on('git:changed', (_e, root) => cb(root)),
  setWindowBg: (color) => ipcRenderer.send('win:bg', color),
  chatStart: (opts) => ipcRenderer.invoke('chat:start', opts),
  chatSessions: (cwd, configDir) => ipcRenderer.invoke('chat:sessions', cwd, configDir),
  chatHistory: (cwd, id, configDir) => ipcRenderer.invoke('chat:history', cwd, id, configDir),
  accountStatus: (configDir) => ipcRenderer.invoke('account:status', configDir),
  chatSend: (id, text) => ipcRenderer.send('chat:send', id, text),
  chatRespond: (id, requestId, response) => ipcRenderer.send('chat:respond', id, requestId, response),
  chatInterrupt: (id) => ipcRenderer.send('chat:interrupt', id),
  chatKill: (id) => ipcRenderer.send('chat:kill', id),
  onChatEvent: (cb) => ipcRenderer.on('chat:event', (_e, id, ev) => cb(id, ev)),
  onChatStderr: (cb) => ipcRenderer.on('chat:stderr', (_e, id, text) => cb(id, text)),
  onChatExit: (cb) => ipcRenderer.on('chat:exit', (_e, id, code) => cb(id, code)),
  createPty: (opts) => ipcRenderer.invoke('pty:create', opts),
  write: (id, data) => ipcRenderer.send('pty:write', id, data),
  resize: (id, cols, rows) => ipcRenderer.send('pty:resize', id, cols, rows),
  kill: (id) => ipcRenderer.send('pty:kill', id),
  onData: (cb) => ipcRenderer.on('pty:data', (_e, id, data) => cb(id, data)),
  onExit: (cb) => ipcRenderer.on('pty:exit', (_e, id, code) => cb(id, code)),
});
